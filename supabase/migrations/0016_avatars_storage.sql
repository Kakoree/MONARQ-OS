-- MONARQ OS — Phase 9: avatar storage bucket + policies
-- Run after 0015_member_directory_view.sql.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('avatars', 'avatars', true, 2097152, array['image/png', 'image/jpeg', 'image/webp'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- Uploaded objects are namespaced as avatars/{user_id}/..., so
-- storage.foldername(name) → the first path segment is the owning user.
create policy "avatar_insert_own"
  on storage.objects for insert
  with check (
    bucket_id = 'avatars'
    and auth.uid()::text = (storage.foldername(name))[1]
  );

create policy "avatar_update_own"
  on storage.objects for update
  using (
    bucket_id = 'avatars'
    and auth.uid()::text = (storage.foldername(name))[1]
  )
  with check (
    bucket_id = 'avatars'
    and auth.uid()::text = (storage.foldername(name))[1]
  );

create policy "avatar_delete_own"
  on storage.objects for delete
  using (
    bucket_id = 'avatars'
    and auth.uid()::text = (storage.foldername(name))[1]
  );

-- The bucket is public, so reads via the public URL already bypass this,
-- but this keeps direct storage.objects queries consistent too.
create policy "avatar_select_public"
  on storage.objects for select
  using (bucket_id = 'avatars');
